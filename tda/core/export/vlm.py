def graph_version_of(db: Db, desktop: int) -> Optional[str]:
    """Which constraint graph this export shipped, when the tool can say.

    Read through :func:`getattr` on purpose: this export has to keep working on
    a build where :func:`tda.core.graph.graph_version` is not there yet, and a
    stamp nobody can compute is exactly what ``None`` has always meant here.
    """
    try:
        from tda.core import graph as graph_mod
    except ImportError:  # pragma: no cover - the module is part of the package
        return None
    stamp = getattr(graph_mod, "graph_version", None)
    if stamp is None:
        return None
    try:
        value = stamp(db, int(desktop))
    except (TypeError, ValueError, sqlite3.Error):
        return None
    return None if value is None else str(value)


def manifest_path(out_jsonl: str) -> Path:
    """Where the image manifest of ``out_jsonl`` goes.

    Named after the JSONL rather than a bare ``images_manifest.jsonl``: the CLI
    writes one file per view into one directory, and a fixed name would have the
    four views overwrite each other's manifest.
    """
    out = Path(out_jsonl)
    return out.with_name(out.stem + ".images_manifest.jsonl")


def summary_path(out_jsonl: str) -> Path:
    """Where the counts, the exclusions and the shortcut table go."""
    out = Path(out_jsonl)
    return out.with_name(out.stem + ".summary.json")


def oracle_path(out_jsonl: str) -> Path:
    """Where the label-side world tables go (W3b).

    One ``{"type": "desktop"}`` line per desktop -- its instances (class, wording,
    match class, parent), its active edges and its named action log -- and one
    ``{"type": "frame"}`` line per image a record names, with the state machine's
    state and placement of every instance and, **only on an image with
    confirmed rows**, that view's visibility. The scorer grades V7 against it,
    ``scripts/vlm_references.py`` builds the state-oracle and protocol-prior
    references from it; nothing in it is ever shown to a model under test.
    """
    out = Path(out_jsonl)
    return out.with_name(out.stem + ".oracle.jsonl")


def siblings(out_jsonl: str) -> list[Path]:
    """Every file an export writes beside its JSONL.

    An export that found nothing removes the JSONL (an empty artefact is the one
    that gets shipped) and these have to go with it, or the next run reads a
    manifest and a summary that describe a file nobody wrote.
    """
    return [manifest_path(out_jsonl), summary_path(out_jsonl), oracle_path(out_jsonl)]



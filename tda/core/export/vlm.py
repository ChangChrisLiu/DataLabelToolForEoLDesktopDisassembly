def view_has_confirmed(db: Db, desktop: int, view: str) -> bool:
    """Has anybody confirmed anything of this view on this desktop? (W3b)

    A frame signed off as a whole, or one frozen row. Today the answer is yes
    for the scanner and no for OAK1 / OAK2 / RealSense; a view answering no is
    exported without compiling or reading a single row of it -- its records are
    the state machine's, about a picture.
    """
    hit = db.conn.execute(
        "SELECT 1 FROM frame WHERE desktop=? AND view=? AND review_status=? "
        "UNION ALL SELECT 1 FROM compiled_mask WHERE desktop=? AND view=? "
        "AND status=? LIMIT 1",
        (int(desktop), view, VERIFIED, int(desktop), view, VERIFIED)).fetchone()
    return hit is not None


def _read_view(db: Db, ctx: DesktopCtx, desktop: int, view: str,
               disputed: set[int], only_verified: bool,
               labelled: bool = True
               ) -> tuple[dict[int, FrameData], list[int]]:
    """Every exportable frame of one view, with its rows slimmed of their masks.

    A frame the camera never took (``missing``, task U38) is not a frame: no
    question may show it. ``labelled=False`` -- nothing of this view is
    confirmed on this desktop (:func:`view_has_confirmed`, W3b) -- reads no row
    at all: whatever the propagation drew there nobody looked at, so neither a
    box nor a visibility of it reaches a record (:attr:`FrameData.confirmed`).
    """
    frames: dict[int, FrameData] = {}
    order: list[int] = []
    for row in db.frames_for(desktop, view):
        step = int(row["step"])
        if not ctx.exportable(step):
            continue  # an `ignore` step is no moment of the teardown
        if row.get("missing"):
            continue  # this camera has no picture of the step
        key = FrameKey(desktop, step, view)
        # no 框外零件 (task U18): nothing outside the machine is asked about;
        # and nothing at all of a view nobody confirmed anything of (W3b)
        compiled = ({inst: row for inst, row in db.compiled(key).items()
                     if not is_context_key(inst)} if labelled else {})
        # a frame somebody is still arguing about answers nothing confirmed
        verified = step not in disputed and frame_is_verified(db, key, compiled)
        slim = {inst: slim_row(r) for inst, r in compiled.items()}
        for inst, r in compiled.items():
            slim[inst]["status"] = r.get("status")
        # 「被线挡住」 (task U15): what hides a part in its place, nobody labels it
        for inst, fo in db.frame_overrides(key).items():
            if fo.occluder and inst in slim:
                slim[inst]["occluder"] = fo.occluder
        frames[step] = FrameData(
            step=step, image=frame_file_name(row, key),
            image_id=opaque_image_id(desktop, view, step), verified=verified,
            rows=slim, pointable=pointable_rows(ctx, slim, only_verified),
            confirmed=labelled,
        )
        order.append(step)
    return frames, order


def _other_views(db: Db, ctx: DesktopCtx, desktop: int, view: str,
                 only_verified: bool, service: TruthService
                 ) -> dict[str, dict[int, FrameData]]:
    """The *later* views' frames, for V15 only.

    A cross-view record belongs to exactly one file, so it is written by the
    view that comes first in :data:`~tda.core.model.VIEWS`: exporting all four
    views therefore yields each unordered pair once, not twice.

    An open conflict in one of those views does **not** refuse this export. The
    refusal belongs to the view being published -- a disagreement about a
    RealSense frame is not a reason to withhold the scanner's questions -- so
    the conflicted frames are simply marked unverified here, and V15, which only
    speaks about confirmed frames, passes over them. It reads the other views,
    so it refreshes them too: a cross-view answer off a stale cache would be a
    cross-view answer about an edit nobody made.

    A view nothing of which is confirmed on this desktop is neither refreshed
    nor read row by row (W3b): V15-moment needs its pictures and the step they
    were taken at, nothing else.
    """
    out: dict[str, dict[int, FrameData]] = {}
    for other in VIEWS:
        if view_index(other) <= view_index(view):
            continue
        if not db.frames_for(desktop, other):
            continue
        labelled = view_has_confirmed(db, desktop, other)
        if labelled:
            service.ensure_fresh(desktop, other, only_verified)
        disputed = conflicted_steps(service, desktop, other, allow_conflicts=True)
        frames, _ = _read_view(db, ctx, desktop, other, disputed, only_verified,
                               labelled)
        if frames:
            out[other] = frames
    return out


def _write_manifest(path: Path, images: dict[str, tuple]) -> None:
    """One line per frame a prompt referred to, plus a header naming the salt.

    ``roi`` (W3b) is the pose segment's ROI ``[x0, y0, x1, y1]`` of that frame,
    or absent: ``scripts/vlm_to_chat.py --roi view`` crops to it without a DB.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps({"type": "header", "salt": IMAGE_ID_SALT,
                             "algorithm": "sha256", "digest_chars": 16,
                             "body": "<salt>|<desktop>|<view>|<step>"},
                            ensure_ascii=False) + "\n")
        for image_id in sorted(images):
            desktop, view, step, rel, roi = images[image_id]
            line = {"image": image_id, "path": rel, "desktop": desktop,
                    "view": view, "step": step}
            if roi is not None:
                line["roi"] = list(roi)
            fh.write(json.dumps(line, ensure_ascii=False) + "\n")


def _dumps(value) -> str:
    """One JSONL line, keys sorted so two exports stay byte-identical."""
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def _desktop_world(tc: TaskCtx) -> dict:
    """The oracle's per-desktop line: instances, active edges, named log (W3b)."""
    ctx = tc.ctx
    instances = {}
    for key, rec in sorted(ctx.instances.items()):
        if ctx.cls_of(key) is None:
            continue
        instances[key] = {
            "class": rec.cls, "label": instance_label(key, rec, ctx.tax),
            "match_class": match_class(ctx, key),
            "attrs": {k: rec.attrs[k] for k in ("role", "kind", "captive", "of")
                      if k in rec.attrs},
            "parent": rec.parent, "attached": bool(rec.attached),
            "group_id": rec.group_id, "group_order": rec.group_order,
        }
    edges = [{"type": e.type, "target": e.target, "blocker": e.blocker,
              "necessity": e.necessity, "mode": e.mode, "source": e.source,
              "status": e.status}
             for e in sorted(active_edges(tc.edges),
                             key=lambda e: (e.type, e.target, e.blocker))]
    log = []
    for step in tc.log_steps:
        for action in tc.named_actions(step):
            log.append({"step": int(step), "idx": int(action.idx), "verb": action.verb,
                        "target": action.target,
                        "class": target_class(ctx, action.target),
                        "match_class": match_class(ctx, action.target),
                        "changes_state": tc.changes_state(action)})
    return {"type": "desktop", "desktop": int(tc.desktop),
            "model_family": tc.meta.get("model_family"), "instances": instances,
            "edges": edges, "log": log}


def _frame_table(tc: TaskCtx, view: str, data: FrameData) -> dict:
    """The oracle's per-image line: the state machine's table of that moment.

    Visibility only where this image carries confirmed rows -- an unlabelled
    view's visibility is never implied (W3b).
    """
    state = tc.ctx.state_at(data.step)
    table = {}
    for key, inst in sorted(state.items()):
        if key not in tc.ctx.instances and not key.startswith("cable:"):
            continue
        entry = {"state": inst.state, "placement": inst.placement}
        if data.confirmed and key in data.rows:
            entry["visibility"] = data.rows[key].get("visibility")
        table[key] = entry
    return {"type": "frame", "image": data.image_id, "desktop": int(tc.desktop),
            "view": view, "step": int(data.step), "confirmed": bool(data.confirmed),
            "state": table}


